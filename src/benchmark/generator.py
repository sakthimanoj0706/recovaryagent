"""
Synthetic Payment Population Generator for RecoverAI Economic Benchmark.

Generates realistic, statistically diverse synthetic payment lifecycles
across 12 financial archetypes with deterministic pseudo-random seeding.

ALL DATA GENERATED BY THIS MODULE IS SYNTHETIC FOR BENCHMARK PURPOSES.
NOT REAL PAYMENT DATA.
"""

import random
from typing import List, Dict, Any, Tuple, Optional
from datetime import datetime, timedelta, timezone
from dataclasses import dataclass

from state_engine.models import PaymentRecord, Event
from .models import BenchmarkArchetype, BenchmarkConfig


@dataclass
class SyntheticLifecycle:
    """A single synthetic payment case with ground truth lifecycle metadata."""
    payment: PaymentRecord
    events: List[Event]
    order_events: Optional[List[Event]]
    archetype: BenchmarkArchetype
    ground_truth_collected: float
    is_genuine_loss: bool
    is_hard_decline: bool
    has_duplicate_webhook: bool
    has_conflicting_webhook: bool
    has_late_capture: bool
    is_partial_capture: bool
    is_refunded: bool
    true_customer_willingness: float  # Hidden ground truth probability that customer would pay if reached


class SyntheticPopulationGenerator:
    """
    Deterministic synthetic payment lifecycle generator.
    """

    PAYMENT_METHODS = ["upi", "card", "netbanking", "wallet"]
    METHOD_WEIGHTS = [0.55, 0.28, 0.12, 0.05]

    CUSTOMER_SEGMENTS = ["high_value_repeat", "returning", "standard", "new"]
    SEGMENT_WEIGHTS = [0.15, 0.35, 0.35, 0.15]

    SOFT_ERROR_CODES = [
        "INSUFFICIENT_FUNDS",
        "BANK_TIMEOUT",
        "NETWORK_ERROR",
        "OTP_TIMEOUT",
        "UPI_PIN_TIMEOUT",
        "BANK_SERVER_BUSY",
    ]

    HARD_ERROR_CODES = [
        "CARD_BLOCKED",
        "CARD_EXPIRED",
        "BAD_VPA",
        "INVALID_ACCOUNT",
        "USER_CANCELLED",
        "TRANSACTION_NOT_PERMITTED",
    ]

    def __init__(self, seed: int = 42):
        self.seed = seed
        self.rng = random.Random(seed)

    def generate_population(self, config: Optional[BenchmarkConfig] = None) -> List[SyntheticLifecycle]:
        """
        Generate a synthetic population of payment lifecycles based on configuration.
        """
        cfg = config or BenchmarkConfig()
        total_payments = cfg.payments
        weights_map = cfg.archetype_weights

        # Normalize weights
        archetypes = list(weights_map.keys())
        probabilities = [weights_map[a] for a in archetypes]
        prob_sum = sum(probabilities)
        normalized_probs = [p / prob_sum for p in probabilities]

        population: List[SyntheticLifecycle] = []
        base_time = datetime(2026, 8, 28, 10, 0, 0, tzinfo=timezone.utc)

        for i in range(total_payments):
            # Select archetype deterministically
            chosen_archetype_str = self.rng.choices(archetypes, weights=normalized_probs, k=1)[0]
            archetype = BenchmarkArchetype(chosen_archetype_str)
            
            lifecycle = self._generate_single_lifecycle(i, archetype, base_time)
            population.append(lifecycle)

        return population

    def _generate_amount(self) -> float:
        """
        Generate realistic ticket sizes using log-normal distribution.
        Produces realistic ecommerce ticket sizes: ₹150 to ₹100,000, median ~₹1,500, mean ~₹3,500.
        """
        raw = self.rng.lognormvariate(mu=7.2, sigma=0.95)  # median ~ e^7.2 = 1339
        clamped = max(100.0, min(150000.0, raw))
        # Round to whole rupees or realistic price points
        return float(round(clamped))

    def _generate_single_lifecycle(
        self,
        index: int,
        archetype: BenchmarkArchetype,
        base_time: datetime,
    ) -> SyntheticLifecycle:
        """Construct a single synthetic payment lifecycle according to its archetype."""
        payment_id = f"pay_syn_{index:06d}"
        order_id = f"ord_syn_{index:06d}"
        amount = self._generate_amount()
        method = self.rng.choices(self.PAYMENT_METHODS, weights=self.METHOD_WEIGHTS, k=1)[0]
        segment = self.rng.choices(self.CUSTOMER_SEGMENTS, weights=self.SEGMENT_WEIGHTS, k=1)[0]
        
        # Payment creation timestamp
        offset_mins = self.rng.randint(0, 10000)
        t0 = base_time + timedelta(minutes=offset_mins)
        t0_str = t0.isoformat()

        payment = PaymentRecord(
            payment_id=payment_id,
            order_id=order_id,
            amount=amount,
            method=method,
            customer_segment=segment,
            created_at=t0_str,
            metadata={"synthetic_seed": self.seed, "archetype": archetype.value},
        )

        events: List[Event] = []
        order_events: Optional[List[Event]] = None
        
        ground_truth_collected = 0.0
        is_genuine_loss = False
        is_hard_decline = False
        has_duplicate_webhook = False
        has_conflicting_webhook = False
        has_late_capture = False
        is_partial_capture = False
        is_refunded = False
        willingness = self.rng.uniform(0.35, 0.95) if segment in ["high_value_repeat", "returning"] else self.rng.uniform(0.10, 0.65)

        # -----------------------------------------------------------------
        # 1. SUCCESS: Clean first-attempt capture
        # -----------------------------------------------------------------
        if archetype == BenchmarkArchetype.SUCCESS:
            events.append(Event(event="payment.created", payment_id=payment_id, order_id=order_id, ts=t0_str, amount=amount))
            t1 = (t0 + timedelta(seconds=self.rng.randint(2, 10))).isoformat()
            events.append(Event(event="payment.captured", payment_id=payment_id, order_id=order_id, ts=t1, amount=amount))
            ground_truth_collected = amount

        # -----------------------------------------------------------------
        # 2. SOFT_FAILURE: Genuine lost payment eligible for recovery
        # -----------------------------------------------------------------
        elif archetype == BenchmarkArchetype.SOFT_FAILURE:
            err = self.rng.choice(self.SOFT_ERROR_CODES)
            events.append(Event(event="payment.created", payment_id=payment_id, order_id=order_id, ts=t0_str, amount=amount))
            t1 = (t0 + timedelta(seconds=self.rng.randint(3, 12))).isoformat()
            events.append(Event(event="payment.failed", payment_id=payment_id, order_id=order_id, ts=t1, error_code=err, hardness="soft"))
            is_genuine_loss = True
            ground_truth_collected = 0.0

        # -----------------------------------------------------------------
        # 3. HARD_DECLINE: Permanent card/VPA failure (unrecoverable via retry)
        # -----------------------------------------------------------------
        elif archetype == BenchmarkArchetype.HARD_DECLINE:
            err = self.rng.choice(self.HARD_ERROR_CODES)
            is_hard_decline = True
            events.append(Event(event="payment.created", payment_id=payment_id, order_id=order_id, ts=t0_str, amount=amount))
            t1 = (t0 + timedelta(seconds=self.rng.randint(2, 8))).isoformat()
            events.append(Event(event="payment.failed", payment_id=payment_id, order_id=order_id, ts=t1, error_code=err, hardness="hard"))
            is_genuine_loss = True
            ground_truth_collected = 0.0

        # -----------------------------------------------------------------
        # 4. ALREADY_RECOVERED: Late-Auth Flip-Flop (Failed at T+5s, Captured at T+25s)
        # -----------------------------------------------------------------
        elif archetype == BenchmarkArchetype.ALREADY_RECOVERED:
            has_late_capture = True
            events.append(Event(event="payment.created", payment_id=payment_id, order_id=order_id, ts=t0_str, amount=amount))
            t1 = (t0 + timedelta(seconds=5)).isoformat()
            events.append(Event(event="payment.failed", payment_id=payment_id, order_id=order_id, ts=t1, error_code="BANK_TIMEOUT", hardness="soft"))
            t2 = (t0 + timedelta(seconds=25)).isoformat()
            events.append(Event(event="payment.captured", payment_id=payment_id, order_id=order_id, ts=t2, amount=amount))
            ground_truth_collected = amount

        # -----------------------------------------------------------------
        # 5. UNCERTAIN: In-flight / pending bank confirmation
        # -----------------------------------------------------------------
        elif archetype == BenchmarkArchetype.UNCERTAIN:
            events.append(Event(event="payment.created", payment_id=payment_id, order_id=order_id, ts=t0_str, amount=amount))
            t1 = (t0 + timedelta(seconds=4)).isoformat()
            events.append(Event(event="payment.pending", payment_id=payment_id, order_id=order_id, ts=t1))
            ground_truth_collected = 0.0

        # -----------------------------------------------------------------
        # 6. EXCEPTION: Settlement / fee mismatch requiring operations audit
        # -----------------------------------------------------------------
        elif archetype == BenchmarkArchetype.EXCEPTION:
            events.append(Event(event="payment.created", payment_id=payment_id, order_id=order_id, ts=t0_str, amount=amount))
            t1 = (t0 + timedelta(seconds=5)).isoformat()
            events.append(Event(event="payment.captured", payment_id=payment_id, order_id=order_id, ts=t1, amount=amount))
            t2 = (t0 + timedelta(minutes=5)).isoformat()
            # Mismatched settlement amount
            events.append(Event(event="settlement.processed", payment_id=payment_id, order_id=order_id, ts=t2, amount=amount * 0.90, fee=amount * 0.05, tax=amount * 0.01))
            ground_truth_collected = 0.0

        # -----------------------------------------------------------------
        # 7. PARTIAL_CAPTURE: Partial bank capture (e.g. 60% of original amount)
        # -----------------------------------------------------------------
        elif archetype == BenchmarkArchetype.PARTIAL_CAPTURE:
            is_partial_capture = True
            partial_amount = float(round(amount * self.rng.uniform(0.40, 0.75)))
            events.append(Event(event="payment.created", payment_id=payment_id, order_id=order_id, ts=t0_str, amount=amount))
            t1 = (t0 + timedelta(seconds=5)).isoformat()
            events.append(Event(event="payment.failed", payment_id=payment_id, order_id=order_id, ts=t1, error_code="INSUFFICIENT_FUNDS", hardness="soft"))
            t2 = (t0 + timedelta(seconds=45)).isoformat()
            events.append(Event(event="payment.partially_captured", payment_id=payment_id, order_id=order_id, ts=t2, amount=partial_amount))
            ground_truth_collected = partial_amount

        # -----------------------------------------------------------------
        # 8. REFUNDED: Captured and subsequently refunded
        # -----------------------------------------------------------------
        elif archetype == BenchmarkArchetype.REFUNDED:
            is_refunded = True
            events.append(Event(event="payment.created", payment_id=payment_id, order_id=order_id, ts=t0_str, amount=amount))
            t1 = (t0 + timedelta(seconds=5)).isoformat()
            events.append(Event(event="payment.captured", payment_id=payment_id, order_id=order_id, ts=t1, amount=amount))
            t2 = (t0 + timedelta(minutes=15)).isoformat()
            events.append(Event(event="payment.refunded", payment_id=payment_id, order_id=order_id, ts=t2, amount=amount))
            ground_truth_collected = 0.0

        # -----------------------------------------------------------------
        # 9. DUPLICATE: Repeated identical webhook delivered twice
        # -----------------------------------------------------------------
        elif archetype == BenchmarkArchetype.DUPLICATE:
            has_duplicate_webhook = True
            events.append(Event(event="payment.created", payment_id=payment_id, order_id=order_id, ts=t0_str, amount=amount))
            t1 = (t0 + timedelta(seconds=5)).isoformat()
            events.append(Event(event="payment.captured", payment_id=payment_id, order_id=order_id, ts=t1, amount=amount))
            events.append(Event(event="payment.captured", payment_id=payment_id, order_id=order_id, ts=t1, amount=amount))
            ground_truth_collected = amount

        # -----------------------------------------------------------------
        # 10. OUT_OF_ORDER: Captured webhook arrives before failure webhook
        # -----------------------------------------------------------------
        elif archetype == BenchmarkArchetype.OUT_OF_ORDER:
            t_created = t0.isoformat()
            t_failed = (t0 + timedelta(seconds=5)).isoformat()
            t_captured = (t0 + timedelta(seconds=20)).isoformat()
            # Shuffled arrival order: Captured, Created, Failed
            events.append(Event(event="payment.captured", payment_id=payment_id, order_id=order_id, ts=t_captured, amount=amount))
            events.append(Event(event="payment.created", payment_id=payment_id, order_id=order_id, ts=t_created, amount=amount))
            events.append(Event(event="payment.failed", payment_id=payment_id, order_id=order_id, ts=t_failed, error_code="BANK_TIMEOUT", hardness="soft"))
            ground_truth_collected = amount

        # -----------------------------------------------------------------
        # 11. TIMEOUT: Provider gateway dropped connection
        # -----------------------------------------------------------------
        elif archetype == BenchmarkArchetype.TIMEOUT:
            events.append(Event(event="payment.created", payment_id=payment_id, order_id=order_id, ts=t0_str, amount=amount))
            t1 = (t0 + timedelta(seconds=12)).isoformat()
            events.append(Event(event="payment.failed", payment_id=payment_id, order_id=order_id, ts=t1, error_code="GATEWAY_TIMEOUT", hardness="soft"))
            is_genuine_loss = True
            ground_truth_collected = 0.0

        # -----------------------------------------------------------------
        # 12. LATE_CAPTURE: Captured after long delay (e.g. 45 minutes)
        # -----------------------------------------------------------------
        elif archetype == BenchmarkArchetype.LATE_CAPTURE:
            has_late_capture = True
            events.append(Event(event="payment.created", payment_id=payment_id, order_id=order_id, ts=t0_str, amount=amount))
            t1 = (t0 + timedelta(seconds=5)).isoformat()
            events.append(Event(event="payment.failed", payment_id=payment_id, order_id=order_id, ts=t1, error_code="BANK_TIMEOUT", hardness="soft"))
            t2 = (t0 + timedelta(minutes=45)).isoformat()
            events.append(Event(event="payment.captured", payment_id=payment_id, order_id=order_id, ts=t2, amount=amount))
            ground_truth_collected = amount

        return SyntheticLifecycle(
            payment=payment,
            events=events,
            order_events=order_events,
            archetype=archetype,
            ground_truth_collected=ground_truth_collected,
            is_genuine_loss=is_genuine_loss,
            is_hard_decline=is_hard_decline,
            has_duplicate_webhook=has_duplicate_webhook,
            has_conflicting_webhook=has_conflicting_webhook,
            has_late_capture=has_late_capture,
            is_partial_capture=is_partial_capture,
            is_refunded=is_refunded,
            true_customer_willingness=willingness,
        )
