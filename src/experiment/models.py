"""
Data models for the Autonomous Recovery Experiment & A/B Evaluation (Step 15).
"""

from typing import Dict, Any, List
from datetime import datetime, timezone
import hashlib
import json
import uuid
from pydantic import BaseModel, Field, ConfigDict


class ABTestConfig(BaseModel):
    """Configuration for the A/B test population and economic assumptions."""
    population_size: int = Field(default=1000, description="Number of synthetic payments")
    random_seed: int = Field(default=42, description="Seed for deterministic evaluation")
    gateway_attempt_cost: float = 1.0
    payment_link_cost: float = 1.5
    customer_contact_cost: float = 0.5
    manual_escalation_cost: float = 10.0
    hard_decline_penalty_cost: float = 5.0
    double_recovery_chargeback_cost: float = 25.0


class StrategyResult(BaseModel):
    """The aggregate financial performance of a single strategy."""
    strategy_name: str
    total_recovered: float
    total_withheld: float
    total_escalated: float
    total_pending: float
    total_costs: float
    net_legitimate_value: float
    false_recovery_claims: int
    double_charge_violations: int
    safety_violations: int


class CounterfactualValueProof(BaseModel):
    """
    A cryptographically signed artifact proving the exact, isolated net value
    created by RecoverAI vs a Naive baseline on identical constraints.
    """
    proof_id: str = Field(default_factory=lambda: f"ab_proof_{uuid.uuid4().hex[:12]}")
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    config: ABTestConfig
    
    baseline_result: StrategyResult
    recoverai_result: StrategyResult
    
    incremental_gross_recovery: float = Field(description="Gross additional funds recovered by AI")
    cost_savings: float = Field(description="Costs avoided by intelligent omission vs naive retry")
    incremental_net_value: float = Field(description="Total exact net value generated by AI vs baseline")
    
    safety_violations_prevented: int = Field(description="Number of naive violations stopped by the AI Firewall")
    unnecessary_actions_avoided: int = Field(description="Number of -EV actions omitted by PolicyEngine")
    
    proof_signature_sha256: str = Field(default="", description="Tamper-evident hash of the comparison")

    model_config = ConfigDict(extra="allow")

    def sign_proof(self) -> str:
        """Deterministically seal the proof using SHA-256."""
        payload = {
            "config": self.config.model_dump(),
            "baseline": self.baseline_result.model_dump(),
            "recoverai": self.recoverai_result.model_dump(),
            "incremental_net_value": self.incremental_net_value,
            "safety_violations_prevented": self.safety_violations_prevented
        }
        raw_bytes = json.dumps(payload, sort_keys=True).encode("utf-8")
        sig = hashlib.sha256(raw_bytes).hexdigest()
        self.proof_signature_sha256 = sig
        return sig
